#!/usr/bin/env bash
# tour-stills.sh: keepmum.app's app tour (site/tour.js) from the app itself. The app renders the
# screens the tour shows as stills, with the tour's timing (Tour.stills, mac/Sources/Keepmum/Tour.swift);
# this makes the stills WebP in site/img/tour/ and the timing site/tour-data.js, a script, since
# the page's Content Security Policy lets it load scripts from itself but fetch nothing.
#
#   mac/tour-stills.sh        (brew install webp, for cwebp)
set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

(cd "$root/mac" && swift build -c release >/dev/null)
"$root/mac/.build/release/Keepmum" --tour-stills "$work"

out=$root/site/img/tour
rm -rf "$out"
mkdir -p "$out"
for png in "$work"/*.png; do
  # The app's screens are flat color and text: quality 82 keeps the small text clean.
  cwebp -quiet -q 82 -m 6 -alpha_q 100 "$png" -o "$out/$(basename "$png" .png).webp"
done

{
  echo "// Generated by mac/tour-stills.sh from the app (Tour.stills in mac/Sources/Keepmum/Tour.swift): do not edit."
  echo "// The app tour's timing, for site/tour.js. Its stills are in img/tour/."
  printf "window.keepmumTour = "
  # Compact, with each number to three places (Swift writes 3.4 as 3.3999999999999999).
  python3 -I -c 'import json, sys
def r(v):
    if isinstance(v, float): return round(v, 3)
    if isinstance(v, list): return [r(x) for x in v]
    if isinstance(v, dict): return {k: r(x) for k, x in v.items()}
    return v
print(json.dumps(r(json.load(open(sys.argv[1]))), separators=(",", ":"), ensure_ascii=False) + ";")' "$work/tour.json"
} >"$root/site/tour-data.js"

du -ch "$out"/*.webp | tail -1 | sed "s|total|in $out|"
